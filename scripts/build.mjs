import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { loadSiteData } from "./content.mjs";
const require=createRequire(import.meta.url);
const {build}=require("esbuild");
const React=require("react");
const {renderToString}=require("react-dom/server");
const root=path.resolve(import.meta.dirname,"..");
const output=path.join(root,"dist");
const cache=path.join(root,".cache");
if(path.dirname(output)!==root||path.basename(output)!=="dist")throw Error("Unexpected output directory");
fs.rmSync(output,{recursive:true,force:true});
fs.mkdirSync(path.join(output,"assets"),{recursive:true});fs.mkdirSync(cache,{recursive:true});
const nodePaths=(process.env.NODE_PATH||"").split(path.delimiter).filter(Boolean);
const common={absWorkingDir:root,bundle:true,jsx:"automatic",nodePaths,logLevel:"warning"};
await build({...common,entryPoints:["scripts/ssr.tsx"],outfile:path.join(cache,"ssr.cjs"),platform:"node",format:"cjs",external:["react","react/*","react-dom","react-dom/*"]});
const {StaticPage,defaultProfile,defaultProjects}=require(path.join(cache,"ssr.cjs"));
await build({...common,entryPoints:["app/client.tsx"],outfile:path.join(output,"assets/site.js"),platform:"browser",format:"iife",target:"es2020",minify:true,define:{"process.env.NODE_ENV":'"production"'},legalComments:"eof"});
const contentFile=path.join(root,"content/site.json");
if(!fs.existsSync(contentFile))fs.writeFileSync(contentFile,JSON.stringify({profile:defaultProfile,entries:defaultProjects},null,2));
const sourceData=loadSiteData(root,{profile:defaultProfile,entries:defaultProjects});
const data={profile:sourceData.profile,entries:sourceData.entries.filter(e=>e.status==="published")};
if(!data.profile||!Array.isArray(data.entries))throw Error("Invalid site content");
fs.cpSync(path.join(root,"public"),output,{recursive:true});
const styles=["globals","home","projects","project-media","profile-contact","meadow","recognition","site-theme","reading"];
fs.writeFileSync(path.join(output,"assets/site.css"),styles.map(name=>fs.readFileSync(path.join(root,"app",name+".css"),"utf8")).join("\n"));
const escape=value=>String(value).replace(/&/g,"&amp;").replace(/</g,"&lt;").replace(/>/g,"&gt;").replace(/"/g,"&quot;");
const routes=["/","/work","/reading","/journal","/contact",...data.entries.map(e=>`/post/${e.id}`)];
const titles={"/work":{zh:"项目与经历",en:"Projects & experience"},"/reading":{zh:"阅读",en:"Reading"},"/journal":{zh:"生活手记",en:"Journal"},"/contact":{zh:"联系我",en:"Contact"}};
let pageCount=0;
function writePage(route,lang,is404=false){
  const part=route==="/"?"":route.slice(1)+"/";
  const relativeFile=is404?"404.html":(lang==="en"?"en/":"")+part+"index.html";
  const depth=relativeFile.split("/").length-1;
  const prefix=depth?"../".repeat(depth):"./";
  const props={route,lang,prefix,data};
  const entry=data.entries.find(e=>route===`/post/${e.id}`);
  const title=entry?(entry.title[lang]||entry.title.zh):titles[route]?.[lang]||(lang==="zh"?"彭筱 · 水与生活之间":"Water & everyday life");
  const markup=renderToString(React.createElement(StaticPage,props));
  const json=JSON.stringify(props).replace(/</g,"\\u003c").replace(/\u2028/g,"\\u2028").replace(/\u2029/g,"\\u2029");
  const html=`<!doctype html>\n<html lang="${lang==="zh"?"zh-CN":"en"}"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>${escape(title)} · XIAO PENG</title><meta name="description" content="${escape(entry?.summary[lang]||data.profile.intro[lang].split("\n")[0])}"><link rel="icon" href="${prefix}favicon.svg"><link rel="stylesheet" href="${prefix}assets/site.css"></head><body><div id="root">${markup}</div><script id="page-data" type="application/json">${json}</script><script src="${prefix}assets/site.js" defer></script></body></html>\n`;
  const file=path.join(output,relativeFile);fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,html);pageCount++;
}
for(const lang of ["zh","en"])for(const route of routes)writePage(route,lang);
writePage("/404","zh",true);
fs.writeFileSync(path.join(output,".nojekyll"),"");
fs.writeFileSync(path.join(output,"README.md"),fs.readFileSync(path.join(root,"README.md"),"utf8"));
console.log(JSON.stringify({pages:pageCount,output,articles:data.entries.length}));
